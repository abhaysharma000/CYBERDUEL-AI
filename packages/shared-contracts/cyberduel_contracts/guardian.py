"""Shared data contracts and Pydantic schemas for CyberDuel Guardian supervisor."""

from __future__ import annotations

from datetime import UTC, datetime
from enum import StrEnum
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field


class GuardianState(StrEnum):
    """Explicit, persisted state machine for CyberDuel Guardian missions."""

    IDLE = "idle"
    RESEARCHING = "researching"
    ANALYZING = "analyzing"
    DEFENDING = "defending"
    EVALUATING = "evaluating"
    APPROVAL_PENDING = "approval_pending"
    RELEASED = "released"
    FAILED = "failed"
    REJECTED = "rejected"
    BLOCKED = "blocked"
    NEEDS_REVIEW = "needs_review"


class GuardianDecisionOutcome(StrEnum):
    """User-facing protection decision outcomes coordinated by Guardian."""

    BLOCK = "block"
    WARN = "warn"
    ALLOW = "allow"


class AgentHealthStatus(BaseModel):
    """Health, latency, and operational status of an individual autonomous agent."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    role: str
    status: str = Field(description="'online', 'degraded', 'busy', 'offline'")
    model: str = Field(default="deterministic-baseline")
    provider_type: str = Field(default="qwen")
    last_active_at: datetime | None = None
    latency_ms: float | None = None
    details: dict[str, Any] = Field(default_factory=dict)


class GuardianDecisionExplanation(BaseModel):
    """Evidence-based comparative reasoning generated by Guardian for defensive improvements."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    selected_candidate_id: UUID | None = None
    selected_candidate_version: str | None = None
    threat_priority: str = Field(default="high", description="'critical', 'high', 'medium', 'low'")
    research_priority: str = Field(default="high")
    candidate_priority: str = Field(default="high")
    expected_detection_benefit: str = Field(default="")
    false_positive_concerns: str = Field(default="None identified against held-out benchmark suite")
    evaluator_verdict: str = Field(default="pass")
    release_recommendation: str = Field(default="promote")
    user_impact: str = Field(default="Proactive protection against evasive threat without benign interruption")
    confidence: float = Field(default=0.98, ge=0.0, le=1.0)
    uncertainty: str = Field(default="Low: verified against golden benchmark corpus with zero regressions")
    recommended_next_action: str = Field(default="Deploy cryptographic signed update to edge fleet")
    reasoning_summary: str = Field(default="")


class GuardianActivityEvent(BaseModel):
    """Chronological timeline event recorded during Guardian supervisor execution."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    id: UUID = Field(default_factory=uuid4)
    mission_id: UUID | None = None
    step_name: str
    stage: GuardianState
    message: str
    actor: str = Field(default="guardian")
    evidence: dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class GuardianMissionRequest(BaseModel):
    """Request payload to initiate a supervised research-to-defense mission or challenge."""

    model_config = ConfigDict(extra="forbid")

    mission_name: str = "Autonomous Defense Improvement Mission"
    goal: str = "Discover evasive IDN homoglyphs, synthesize declarative AST rules, and release verified policy"
    target_family: str = "homograph_mimicry"
    scenario_count: int = Field(default=10, ge=2, le=100)
    auto_release: bool = True
    is_live_challenge: bool = False


class GuardianMissionContract(BaseModel):
    """Complete persisted record of a Guardian supervised mission."""

    model_config = ConfigDict(extra="forbid")

    mission_id: UUID
    mission_name: str
    goal: str
    state: GuardianState
    trigger_source: str
    experiment_id: UUID | None = None
    candidate_id: UUID | None = None
    candidate_version: str | None = None
    evaluation_id: UUID | None = None
    release_id: UUID | None = None
    policy_version: str | None = None
    initial_threat_url: str | None = None
    initial_decision: str | None = None
    final_decision: str | None = None
    benign_control_url: str | None = None
    benign_control_decision: str | None = None
    decision_explanation: GuardianDecisionExplanation | None = None
    timeline: list[GuardianActivityEvent] = Field(default_factory=list)
    started_at: datetime
    completed_at: datetime | None = None
    terminal_reason: str | None = None


class GuardianStatusResponse(BaseModel):
    """Live operational telemetry of CyberDuel Guardian and connected agent subsystems."""

    model_config = ConfigDict(extra="forbid")

    guardian_name: str = "CyberDuel Guardian"
    version: str = "1.0.0-supervisor"
    state: GuardianState
    active_mission_id: UUID | None = None
    agent_health: dict[str, AgentHealthStatus] = Field(default_factory=dict)
    qwen_status: dict[str, Any] = Field(default_factory=dict)
    active_policy_version: str = "1.1.0"
    total_missions_executed: int = 0
    latest_decision: GuardianDecisionExplanation | None = None

